const fs = require('fs');
const path = require('path');
const { validateVideos } = require('./checkVideos');
const marker = '// Generated by npm run contentgen:videos. Edit the video catalog and notes.';
const notesMarker = '{/* Composed by contentgen:videos. Edit the shared curriculum chapter. */}';

function composeVideoNotes(root) {
  const folder = path.join(root, 'src/content/videos');
  const sources = JSON.parse(fs.readFileSync(path.join(folder, 'notes-sources.json'), 'utf8'));
  const catalog = JSON.parse(fs.readFileSync(path.join(folder, 'catalog.json'), 'utf8'));
  for (const [slug, chapter] of Object.entries(sources)) {
    if (!/^[a-z0-9-]+$/.test(slug) || !/^[a-z0-9-]+$/.test(chapter))
      throw new Error(`Unsafe video note source: ${slug}`);
    if (!catalog.some((video) => video.slug === slug))
      throw new Error(`Unpublished video note source: ${slug}`);
    const target = path.join(folder, `${slug}.mdx`);
    if (fs.existsSync(target) && !fs.readFileSync(target, 'utf8').startsWith(notesMarker))
      throw new Error(`Refusing to overwrite edited video notes: ${slug}`);
    const prose = fs.readFileSync(
      path.join(root, 'src/content/lesson-walkthroughs/curriculum', `${chapter}.md`), 'utf8',
    ).trim();
    fs.writeFileSync(target, `${notesMarker}\n\n${prose}\n\n## Continue with the implementation\n\nRead the [JavaScript walkthrough](/course/${slug}/javascript) for the current code and links to the other programming languages. Use the [original lesson](/course/${slug}) for practice.\n`);
  }
  for (const filename of fs.readdirSync(folder))
    if (filename.endsWith('.mdx') && !sources[filename.slice(0, -4)]) {
      const target = path.join(folder, filename);
      if (fs.readFileSync(target, 'utf8').startsWith(notesMarker)) fs.unlinkSync(target);
    }
}

function generate({ root = path.resolve(__dirname, '../..'), videos } = {}) {
  if (!videos) {
    composeVideoNotes(root);
    videos = validateVideos();
  }
  const folder = path.join(root, 'src/pages/watch');
  fs.mkdirSync(folder, { recursive: true });
  const published = new Set();
  for (const video of videos) {
    if (!/^[a-z0-9-]+$/.test(video.slug)) throw new Error(`Unsafe video route: ${video.slug}`);
    const filename = `${video.slug}.tsx`;
    published.add(filename);
    const target = path.join(folder, filename);
    if (fs.existsSync(target) && !fs.readFileSync(target, 'utf8').startsWith(marker))
      throw new Error(`Refusing to overwrite handwritten watch page: ${filename}`);
    fs.writeFileSync(
      target,
      `${marker}\nimport * as React from 'react';\nimport WatchPage from 'components/pages/Resources/WatchPage';\nimport Notes from 'content/videos/${video.slug}.mdx';\n\nexport default function Video() {\n  return <WatchPage slug=${JSON.stringify(video.slug)}><Notes /></WatchPage>;\n}\n`,
    );
  }
  for (const filename of fs.readdirSync(folder))
    if (filename.endsWith('.tsx') && !published.has(filename)) {
      const target = path.join(folder, filename);
      if (fs.readFileSync(target, 'utf8').startsWith(marker)) fs.unlinkSync(target);
    }
  return videos.length;
}

if (require.main === module)
  console.log(`Generated ${generate()} static video pages with individual reading companions.`);
module.exports = { generate, marker, composeVideoNotes };
