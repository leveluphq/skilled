// Writes src/content/runnerSpecs.gen.ts: every lesson that has a
// runner.spec.ts, keyed by slug, imported statically so the API routes (and the
// Tests tab) bundle them. Run after adding a spec:
//
//   node scripts/generate-runner-specs.js
//
// A test fails when runnerSpecs.gen.ts is out of date.

const fs = require('fs');
const path = require('path');

const lessonsDir = path.join(__dirname, '../src/content/lessons');
const output = path.join(__dirname, '../src/content/runnerSpecs.gen.ts');

const identifier = (slug) => `spec_${slug.replace(/[^a-zA-Z0-9]/g, '_')}`;

const generate = () => {
  const slugs = fs
    .readdirSync(lessonsDir)
    .filter((slug) => fs.existsSync(path.join(lessonsDir, slug, 'runner.spec.ts')))
    .sort();

  return [
    '// Generated by scripts/generate-runner-specs.js from src/content/lessons/*/runner.spec.ts. Do not edit.',
    "import { LessonSpec } from 'utils/shared/runner/types';",
    ...slugs.map(
      (slug) => `import ${identifier(slug)} from 'content/lessons/${slug}/runner.spec';`,
    ),
    '',
    'const specs: Record<string, LessonSpec> = {',
    ...slugs.map((slug) => `  ${JSON.stringify(slug)}: ${identifier(slug)},`),
    '};',
    '',
    'export default specs;',
    '',
  ].join('\n');
};

module.exports = { generate, output };

if (require.main === module) {
  fs.writeFileSync(output, generate());
  console.log(`Wrote ${path.relative(process.cwd(), output)}`);
}
