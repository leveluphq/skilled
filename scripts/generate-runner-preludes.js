// Embeds each language's runner prelude (src/services/server/runner/preludes/*)
// as a string in preludes.gen.ts, so the API routes bundle exactly the text the
// conformance suite runs. Run after editing a prelude:
//
//   node scripts/generate-runner-preludes.js
//
// A test fails when preludes.gen.ts is out of date.

const fs = require('fs');
const path = require('path');

const dir = path.join(__dirname, '../src/services/server/runner/preludes');

const generate = () => {
  const files = fs
    .readdirSync(dir)
    .filter((name) => !name.startsWith('.') && !name.endsWith('.ts'))
    .sort();
  const entries = files.map(
    (name) =>
      `  ${JSON.stringify(name)}: ${JSON.stringify(fs.readFileSync(path.join(dir, name), 'utf8'))},`,
  );

  return [
    '// Generated by scripts/generate-runner-preludes.js from the files in this folder. Do not edit.',
    '/* eslint-disable */',
    'const preludes: Record<string, string> = {',
    ...entries,
    '};',
    '',
    'export default preludes;',
    '',
  ].join('\n');
};

module.exports = { generate, output: path.join(dir, 'preludes.gen.ts') };

if (require.main === module) {
  fs.writeFileSync(module.exports.output, generate());
  console.log(`Wrote ${path.relative(process.cwd(), module.exports.output)}`);
}
