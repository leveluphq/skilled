// Writes src/content/lessonLanguages.gen.ts: for every lesson with a
// runner.spec.ts, the languages it has starter code and a reference solution
// in. A lesson is offered in a language only when both exist (and the
// language's runner is in codingLanguageList). Run after adding a language's
// files to a lesson:
//
//   node scripts/generate-lesson-languages.js
//
// A test fails when lessonLanguages.gen.ts is out of date.

const fs = require('fs');
const path = require('path');

const lessonsDir = path.join(__dirname, '../src/content/lessons');
const output = path.join(__dirname, '../src/content/lessonLanguages.gen.ts');

// The CodingLanguage member for each language's file name
const LANGUAGES = [
  ['Javascript', 'javascript.mdx'],
  ['Typescript', 'typescript.mdx'],
  ['Python', 'python.mdx'],
  ['Java', 'java.mdx'],
  ['Cpp', 'cpp.mdx'],
  ['Csharp', 'csharp.mdx'],
  ['Go', 'go.mdx'],
  ['Kotlin', 'kotlin.mdx'],
  ['Swift', 'swift.mdx'],
  ['Rust', 'rust.mdx'],
];

const hasSolution = (slug, file) => {
  const dir = path.join(lessonsDir, slug, 'Solution/code');
  return (
    fs.existsSync(dir) &&
    fs.readdirSync(dir).some((variant) => fs.existsSync(path.join(dir, variant, file)))
  );
};

const generate = () => {
  const slugs = fs
    .readdirSync(lessonsDir)
    .filter((slug) => fs.existsSync(path.join(lessonsDir, slug, 'runner.spec.ts')))
    .sort();

  return [
    '// Generated by scripts/generate-lesson-languages.js from the lesson folders. Do not edit.',
    "import { CodingLanguage } from 'utils/constants/lesson';",
    '',
    '// The languages each runnable lesson has starter code and a reference solution in',
    'const lessonLanguages: Record<string, CodingLanguage[]> = {',
    ...slugs.map((slug) => {
      const languages = LANGUAGES.filter(
        ([, file]) =>
          fs.existsSync(path.join(lessonsDir, slug, 'UserAnswer', file)) && hasSolution(slug, file),
      ).map(([member]) => `CodingLanguage.${member}`);
      return `  ${JSON.stringify(slug)}: [${languages.join(', ')}],`;
    }),
    '};',
    '',
    'export default lessonLanguages;',
    '',
  ].join('\n');
};

module.exports = { generate, output };

if (require.main === module) {
  fs.writeFileSync(output, generate());
  console.log(`Wrote ${path.relative(process.cwd(), output)}`);
}
